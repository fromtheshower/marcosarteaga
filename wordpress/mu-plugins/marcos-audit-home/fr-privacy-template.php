          <h2 id="privacy-purpose">Pourquoi je les recueille</h2>
          <p>Pour répondre à votre demande et discuter de l’adéquation et des prochaines étapes. C’est le but. Le formulaire envoie un bref accusé de réception automatique; je vous réponds ensuite personnellement. Les données techniques servent au fonctionnement du formulaire et à la prévention des pourriels.</p>
        </section>

        <section aria-labelledby="privacy-use">
          <h2 id="privacy-use">Ce que je ne fais pas</h2>
          <p>Je ne vous ajoute à aucune liste marketing ni infolettre. Je ne vends ni ne loue vos renseignements. J’utilise ce que vous inscrivez uniquement pour répondre à votre demande. Je ne le transmets pas à une agence partenaire à moins que vous choisissiez un mandat distinct de mise en œuvre.</p>
        </section>

        <section aria-labelledby="privacy-where">
          <h2 id="privacy-where">Où vont vos renseignements</h2>
          <p>Les demandes me sont envoyées par courriel à <a href="mailto:marcos@fromtheshower.com">marcos@fromtheshower.com</a> par Google Workspace. Le site est hébergé sur un serveur Plesk. Ces deux fournisseurs traitent les renseignements nécessaires à l’exploitation du site et à l’envoi des courriels; leurs systèmes peuvent traiter ces données à l’extérieur du Québec.</p>
          <p>Si nous travaillons ensemble, l’audit repose sur un accès en lecture seule à vos comptes publicitaires, à vos données analytiques et à vos ventes. Rien n’est modifié, et vos données restent les vôtres.</p>
        </section>

        <section aria-labelledby="privacy-retention">
